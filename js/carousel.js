    // Shuffle array for visual variety
    function shuffle(arr) {
        var a = arr.slice();
        for (var i = a.length - 1; i > 0; i--) {
            var j = Math.floor(Math.random() * (i + 1));
            var temp = a[i];
            a[i] = a[j];
            a[j] = temp;
        }
        return a;
    }

    var shuffled = shuffle(images);

    // Build img elements (two copies for seamless loop)
    function buildImages(imgArray) {
        var frag = document.createDocumentFragment();
        imgArray.forEach(function(filename) {
            var img = document.createElement("img");
            img.src = basePath + filename;
            img.alt = "EED Community Photo";
            img.draggable = false;
            frag.appendChild(img);
        });
        return frag;
    }

